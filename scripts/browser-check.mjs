// Start Vite on port 5174; optionally pass an existing Playwright module path.
import assert from 'node:assert/strict';
import * as rules from '../src/game/game.ts';
import { saveKey, serialize } from '../src/game/save.ts';
const { chromium, expect } = await import(process.env.PLAYWRIGHT_MODULE || process.argv[2] || '@playwright/test');
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(8000);
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.BASE_URL || 'http://localhost:5174');
  const state = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)).game, saveKey);
  const seed = async game => {
    await page.evaluate(({ key, raw }) => localStorage.setItem(key, raw), { key: saveKey, raw: serialize(game) });
    await page.reload();
  };
  const starter = page.getByRole('article', { name: 'Starter earners', exact: true });
  const settings = () => page.getByRole('button', { name: 'Run and settings', exact: true }).click();
  await seed(rules.newGame());
  await expect(page.locator('.earner-family')).toHaveCount(1);
  await expect(starter.getByRole('button', { name: 'Buy Starter', exact: true })).toBeDisabled();
  for (let click = 0; click < 15; click++) await page.getByRole('button', { name: 'Earn gold', exact: true }).click();
  await starter.getByRole('button', { name: 'Buy Starter', exact: true }).click();
  await expect(starter.locator('.owned-count')).toHaveText('1 owned');
  assert.equal((await state()).earners.starter.count, 1);
  await page.reload();
  await expect(starter.locator('.owned-count')).toHaveText('1 owned');
  const funded = { ...rules.newGame(), gold: 1e12, earned: 1e12, totalEarned: 1e12 };
  funded.earners.starter = { count: 100, level: 1 };
  funded.earners.dynamo = { count: 10, level: 0 };
  await seed(funded);
  await expect(page.locator('.earner-family')).toHaveCount(6);
  await starter.getByRole('button', { name: 'Upgrade Starter', exact: true }).click();
  const upgraded = await state();
  assert.deepEqual(upgraded.earners.starter, { count: 100, level: 2 });
  assert.deepEqual(upgraded.earners.dynamo, funded.earners.dynamo);
  assert.equal(rules.production(upgraded, 'starter'), rules.production(funded, 'starter') * 2);
  await starter.getByRole('button', { name: 'Buy Starter', exact: true }).click();
  assert.equal((await state()).earners.starter.count, 101);
  assert.equal((await state()).earners.starter.level, 2);
  assert.equal(await page.getByRole('button', { name: /Inspect|Clear|Retire|Fuse|Add slot/ }).count(), 0);
  assert.equal(await page.getByRole('region', { name: 'Earner details' }).count(), 0);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  const paused = await state();
  await page.waitForTimeout(1100);
  assert.deepEqual(await state(), paused);
  await page.getByRole('button', { name: 'Resume', exact: true }).click();
  await settings();
  const inSettings = await state();
  await page.waitForTimeout(1100);
  assert.deepEqual(await state(), inSettings);
  await page.getByRole('button', { name: /^Prestige ·/ }).click();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  assert.equal((await state()).runNumber, funded.runNumber);
  await page.getByRole('button', { name: /^Prestige ·/ }).click();
  await page.getByRole('button', { name: 'Confirm prestige', exact: true }).click();
  const prestiged = await state();
  assert.equal(rules.ownedCount(prestiged), 0);
  assert.equal(prestiged.earners.starter.level, 0);
  assert.ok(prestiged.prestigePoints > 0);
  await seed(funded);
  await page.locator('.optional-orders > summary').click();
  await expect(page.locator('.order')).toHaveCount(2);
  const beforeClaim = await state();
  await page.locator('.order button:not(:disabled)').first().click();
  const claimed = await state();
  assert.ok(claimed.contract.round > beforeClaim.contract.round);
  assert.equal(rules.income(claimed), rules.income(beforeClaim));
  await settings();
  const backup = await page.evaluate(key => localStorage.getItem(key), saveKey);
  const input = page.getByLabel('Restore backup', { exact: true });
  await input.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{invalid') });
  await expect(page.getByRole('alert')).toHaveText(/Could not read/);
  await input.setInputFiles({ name: 'save.json', mimeType: 'application/json', buffer: Buffer.from(backup) });
  await page.getByRole('button', { name: 'Confirm restore', exact: true }).click();
  await settings();
  await page.getByRole('button', { name: /^Submit score/ }).click();
  await page.getByRole('button', { name: 'Confirm submission', exact: true }).click();
  const submitted = await state();
  assert.equal(submitted.ended, true);
  await page.reload();
  assert.equal((await state()).ended, true);
  await expect(page.getByRole('button', { name: 'Earn gold', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Start next run →', exact: true }).click();
  assert.equal((await state()).runNumber, submitted.runNumber + 1);
  const late = { ...rules.newGame(), gold: 1e43, earned: 1e43, totalEarned: 1e43 };
  for (const type of Object.keys(late.earners)) late.earners[type] = { count: 200, level: 10 };
  await seed(late);
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect(page.locator('.earner-family')).toHaveCount(9);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow at ${width}px`);
    await settings();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Settings overflow at ${width}px`);
    await page.keyboard.press('Escape');
    await expect(page.getByRole('button', { name: 'Run and settings', exact: true })).toBeFocused();
  }
  assert.deepEqual(errors, []);
  console.log('Browser passed: real first purchase, grouped counts, whole-type upgrades, future purchases, no capacity limit or upkeep controls, pause, fresh saves, prestige, orders, restore, submission, keyboard focus, and 320/390/768/1440px layouts.');
} finally { await browser.close(); }
